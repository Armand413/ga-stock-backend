CREATE TABLE utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifiant VARCHAR(80) NOT NULL UNIQUE,
    nom VARCHAR(150) NOT NULL,
    mot_de_passe VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('ADMIN','GESTIONNAIRE','LECTEUR')),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    echecs_connexion INTEGER NOT NULL DEFAULT 0,
    bloque_jusqua TIMESTAMP WITH TIME ZONE
);
CREATE TABLE sessions_acces (
    empreinte VARCHAR(64) PRIMARY KEY,
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    expiration TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_session_utilisateur ON sessions_acces(utilisateur_id);
CREATE INDEX idx_session_expiration ON sessions_acces(expiration);

