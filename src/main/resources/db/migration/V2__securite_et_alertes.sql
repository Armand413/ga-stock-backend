CREATE TABLE alertes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL REFERENCES articles(id),
    cree_le TIMESTAMP WITH TIME ZONE NOT NULL,
    resolue_le TIMESTAMP WITH TIME ZONE,
    acquittee_le TIMESTAMP WITH TIME ZONE,
    acquittee_par BIGINT REFERENCES utilisateurs(id)
);
CREATE INDEX idx_alerte_article ON alertes(article_id, resolue_le);
